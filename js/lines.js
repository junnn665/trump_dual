// 攻撃するときのかけ声（スートごとに数種類）
const ATTACK = {
  S: ['斬る！', '遅い！', '一気に決める！'],
  C: ['押しつぶせ！', 'どっしり行くぞ！', '根っこごと！'],
  H: ['燃えろォ！', '焼き払え！', 'アチチ、いくぜ！'],
  D: ['計算どおり。', '見切った！', '凍りつけ！'],
  X: ['さあ、笑え！', 'トリックの時間だ！', '道化をなめるな！'],
};

const suitOf = (c) => (c.joker ? 'X' : c.suit);

export function summonLine(card) {
  const s = suitOf(card);
  return (SUMMON[s] && SUMMON[s][card.joker ? card.rank : card.rank]) || '';
}

export function attackLine(card, rnd = Math.random) {
  const list = ATTACK[suitOf(card)] || [];
  return list.length ? list[Math.floor(rnd() * list.length)] : '';
}
